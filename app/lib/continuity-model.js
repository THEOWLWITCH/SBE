  const PHONE = /^\+?[\d\s()-]{7,}$/, EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  function splitLine(line) {
    if (line.indexOf('\t') !== -1) return line.split('\t');
    const out = []; let cur = '', q = false;
    for (const ch of line) { if (ch === '"') q = !q; else if ((ch === ',' || ch === ';') && !q) { out.push(cur); cur = ''; } else cur += ch; }
    out.push(cur); return out;
  }
  function parseRoster(text) {
    const lines = String(text || '').replace(/\r/g, '').split('\n').map((l) => l.trim()).filter(Boolean);
    return rosterFromRows(lines.map(splitLine));
  }
  // rows: מערך של שורות (כל שורה מערך תאים). שורת כותרת מזוהה לפי מילים; בלעדיה מזהים לפי התוכן.
  function rosterFromRows(rows) {
    rows = (rows || []).map((r) => (r || []).map((c) => String(c == null ? '' : c).trim())).filter((r) => r.some(Boolean));
    if (!rows.length) return [];
    const head = rows[0], cols = { name: -1, parents: [], phones: [], email: -1 };
    const isHead = head.some((c) => Object.values(HEAD).some((re) => re.test(c))) && !head.some((c) => PHONE.test(c));
    if (isHead) {
      head.forEach((c, i) => {
        if (HEAD.email.test(c)) { if (cols.email < 0) cols.email = i; }
        else if (HEAD.phone.test(c)) cols.phones.push(i);
        else if (HEAD.parent.test(c)) cols.parents.push(i);
        else if (HEAD.name.test(c) && cols.name < 0) cols.name = i;
      });
      if (cols.name < 0) cols.name = 0;
      rows = rows.slice(1);
    }
    return rows.map((r) => {
      if (isHead) {
        return { name: r[cols.name] || '', parent: r[cols.parents[0]] || '', phone: r[cols.phones[0]] || '',
          parent2: r[cols.parents[1]] || '', phone2: r[cols.phones[1]] || '', email: cols.email >= 0 ? r[cols.email] || '' : '' };
      }
      // בלי כותרת: השם בעמודה הראשונה, טלפונים ודוא״ל לפי התוכן, ושמות ההורים לפי הסדר
      const phones = r.filter((c) => PHONE.test(c)), email = r.find((c) => EMAIL.test(c)) || '';
      const words = r.slice(1).filter((c) => c && !PHONE.test(c) && !EMAIL.test(c));
      return { name: r[0] || '', parent: words[0] || '', phone: phones[0] || '', parent2: words[1] || '', phone2: phones[1] || '', email };
    }).filter((x) => x.name);
  }
