  function splitTeams(names, size) {
    const list = (names || []).filter(Boolean), n = list.length;
    if (!n) return [];
    const s = Math.min(5, Math.max(3, size || 4)), count = Math.max(1, Math.round(n / s));
    const teams = Array.from({ length: count }, () => []);
    list.forEach((x, i) => teams[i % count].push(x));
    return teams;
  }
