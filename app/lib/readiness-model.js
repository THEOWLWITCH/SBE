  const END_RX = /(אבדוק|נבדוק|אחזור אליך|אחזור אלייך|נחזור אל|נחליט אחר כך|נחליט אחר-כך|מחכים ל|מחכה ל|נעדכן|אעדכן|עוד לא ידוע|נברר|אברר)/;
  function detectEnds(text) {
    return String(text || '').split(/(?<=[.!?\n])\s+/).map((s) => s.trim()).filter((s) => s.length > 6 && END_RX.test(s)).slice(0, 40);
  }

  function stats(doc) {
    const p = (doc && doc.parts) || {};
    const teams = Array.isArray(p.teams) ? p.teams : [];
    const ends = Array.isArray(p.ends) ? p.ends : [];
    const actions = Array.isArray(p.actions) ? p.actions : [];
    const ex = Array.isArray(p.exercises) ? p.exercises : [];
    const partners = Array.isArray(p.partners) ? p.partners : [];
    const withDeputy = teams.filter((t) => t && t.deputy && t.deputy.name).length;
    return {
      rel: { partners: partners.length, withDeputy, teams: teams.length },
      info: { actionsDone: actions.filter((a) => a && (a.status === 'done' || a.status === 'tested')).length, actions: actions.length, logs: (doc && doc.log || []).length },
      inst: { staffed: teams.filter((t) => t && t.lead && t.lead.name).length, teams: teams.length, exercises: ex.length },
      openEnds: ends.filter((e) => e && e.status !== 'closed').length,
      escalate: ends.filter((e) => ['noOwner', 'escalate'].includes(endState(e))).length
    };
  }
  function independence(doc) {
    const p = (doc && doc.parts) || {};
    const ex = Array.isArray(p.exercises) ? p.exercises : [];
    const ends = Array.isArray(p.ends) ? p.ends : [];
    const actions = Array.isArray(p.actions) ? p.actions : [];
    const gaps = Array.isArray(p.gaps) ? p.gaps : [];
    return {
      built: ex.filter((x) => x && x.builtByTeam).length,
      led: ex.filter((x) => x && x.ledByTeam !== false && x.finishedAt).length,
      deputy: ex.filter((x) => x && x.ledByDeputy).length,
      gaps: gaps.length,
      closed: ends.filter((e) => e && e.status === 'closed' && !e.closedLate).length,
      tested: actions.filter((a) => a && a.status === 'tested').length,
      cycles: ex.filter((x) => x && x.report && x.report.approvedAt && x.ideasDecidedAt).length
    };
  }

