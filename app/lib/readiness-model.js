  function endState(e, now = Date.now()) {
    if (!e || e.status === 'closed') return 'closed';
    if (!e.owner) return 'noOwner';
    const due = e.next ? Date.parse(e.next) : NaN;
    if (Number.isFinite(due) && due < now) return (e.missed || 0) >= 1 ? 'escalate' : 'late';
    return 'ok';
  }
