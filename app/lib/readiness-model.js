  function pick(base, over) {
    if (over == null) return base;
    if (Array.isArray(base)) return base.map((x, i) => pick(x, Array.isArray(over) ? over[i] : undefined));
    if (base && typeof base === 'object') { const o = {}; for (const k of Object.keys(base)) o[k] = pick(base[k], over && over[k]); return o; }
    return typeof over === typeof base && over !== '' ? over : base;
  }
