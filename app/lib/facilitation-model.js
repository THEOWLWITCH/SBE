  // ── הקלט של המנחה → טקסט למודל ──
  function inputText(f) {
    f = f || {};
    const skills = (f.habits || []).map(k => SHIFTS.find(s => s.k === k)).filter(Boolean).map(s => s.skill);
    const L = [];
    const add = (label, v) => { v = String(v == null ? '' : v).trim(); if (v) L.push(label + ': ' + v); };
    add('הקבוצה', f.group); add('גיל', f.age); add('מספר משתתפים', f.size); add('כמה הם מכירים זה את זה', f.familiar);
    add('התפקיד שלי מול הקבוצה', f.role); add('מצב', f.situation); add('מרחב', f.space); add('משך', f.duration);
    add('הנושא', f.topic); add('המטרה — מה הייתי רוצה שיקרה לקבוצה', f.goal);
    add('מה עוד חשוב לדעת על הקבוצה', f.about);
    add('הניסיון שלי בהנחיה', f.experience);
    if (skills.length) L.push('מיומנויות הנחיה שהייתי רוצה שננה תתמקד בהן:\n' + skills.map(h => '- ' + h).join('\n'));
    add('מה מדאיג אותי', f.worry);
    add('שאלה מרכזית לננה', f.question);
    return L.join('\n');
  }

  const arr = v => Array.isArray(v) ? v : [];
  const str = v => typeof v === 'string' ? v : (v == null ? '' : String(v));
  const strs = v => arr(v).map(str).filter(x => x.trim());
  // מנרמל את תשובת המודל: שדה חסר → ריק, כדי שהמסך לא יישבר; מפתחות מקורות שאינם בבנק מסוננים.
  function normalize(doc, knownKeys) {
    const d = doc && typeof doc === 'object' ? doc : {};
    const known = knownKeys ? new Set(knownKeys) : null;
    const basis = v => strs(v).filter(k => !known || known.has(k)).slice(0, 3);
    const q = d.questions && typeof d.questions === 'object' ? d.questions : {};
    const c = d.conversation && typeof d.conversation === 'object' ? d.conversation : null;
    const m = d.mechanism && typeof d.mechanism === 'object' ? d.mechanism : null;
    const r = d.read && typeof d.read === 'object' ? d.read : {};
    const s = d.stance && typeof d.stance === 'object' ? d.stance : {};
    return {
      intro: str(d.intro),
      read: { stage: str(r.stage), needs: strs(r.needs), lens: str(r.lens) },
      stance: { from: str(s.from), to: str(s.to), why: str(s.why) },
      shifts: arr(d.shifts).filter(x => x && (x.skill || x.habit || x.move)).map(x => ({ skill: str(x.skill || x.habit), move: str(x.move), say: str(x.say), lens: str(x.lens), basis: basis(x.basis) })),
      arc: arr(d.arc).filter(x => x && x.phase).map(x => ({ phase: str(x.phase), minutes: str(x.minutes), facilitator: str(x.facilitator),
        say: strs(x.say), structure: str(x.structure), watch: str(x.watch), lens: str(x.lens), basis: basis(x.basis) })),
      questions: { open: strs(q.open), deepen: strs(q.deepen), connect: strs(q.connect), close: strs(q.close) },
      moments: arr(d.moments).filter(x => x && x.moment).map(x => ({ moment: str(x.moment), signs: str(x.signs), do: str(x.do), say: str(x.say), avoid: str(x.avoid), basis: basis(x.basis) })),
      conversation: c && (c.opening || c.goal) ? { with: str(c.with), goal: str(c.goal), setting: str(c.setting), opening: str(c.opening),
        followups: strs(c.followups), closing: str(c.closing), lens: str(c.lens) } : null,
      mechanism: m && (m.title || m.what) ? { title: str(m.title), what: str(m.what), who: str(m.who), rhythm: str(m.rhythm), sign: str(m.sign), lens: str(m.lens), basis: basis(m.basis) } : null,
      worries: arr(d.worries).filter(x => x && x.worry && x.answer).map(x => ({ worry: str(x.worry), answer: str(x.answer) })),
      pocket: strs(d.pocket).slice(0, 10),
      reflect: strs(d.reflect),
      answers: arr(d.answers).filter(x => x && x.question && x.answer).map(x => ({ question: str(x.question), answer: str(x.answer) }))
    };
  }
  // התשובה של המודל → JSON (גם כשנעטף בטקסט או בגדר קוד)
  function parse(text) {
    const t = String(text || '');
    const a = t.indexOf('{'), b = t.lastIndexOf('}');
    if (a < 0 || b <= a) throw new Error('ננה לא החזירה מבנה תקין');
    return JSON.parse(t.slice(a, b + 1));
  }
