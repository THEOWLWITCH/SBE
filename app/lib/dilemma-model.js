  function parseJSON(text) {
    if (typeof text !== 'string') return null;
    const s = text.indexOf('{'), e = text.lastIndexOf('}');
    if (s < 0 || e <= s) return null;
    try { return JSON.parse(text.slice(s, e + 1)); } catch (x) { return null; }
  }
